/*
 * Итерация 2: ШИМ (плавная яркость светодиода).
 *
 * Светодиод подключён к PA0 (TIM2_CH1)
 * Плавно разгорается за 1 сек, плавно гаснет за 1 сек
 * Полный цикл — 2 сек
 *
 * Частота ШИМ: 1000 Гц (1000 ступеней)
 * Тактирование: 8 МГц (HSI)
 */

#include "stm32f1xx.h"

#define LED_PORT    GPIOA
#define LED_PIN     0       // PA0
#define PWM_STEPS   1000    // 1000 ступеней яркости
#define STEP_DELAY  1       // Задержка между шагами (1 мс)

// ============================================================
// SysTick — точная задержка в миллисекундах
// ============================================================

// Счётчик миллисекунд (volatile — меняется в прерывании)
volatile uint32_t msTicks = 0;

// Обработчик прерывания SysTick — вызывается каждую 1 мс
void SysTick_Handler(void) {
    msTicks++;
}

// Настройка SysTick на 1 мс
void SysTick_Init(void) {
    // 8 МГц / 1000 = 8000 тактов на 1 мс
    SysTick->LOAD = 8000 - 1;
    SysTick->VAL = 0;
    // CTRL = 7 = 0b111:
    //   бит 0 (ENABLE)    = 1 → включить SysTick
    //   бит 1 (TICKINT)   = 1 → генерировать прерывание
    //   бит 2 (CLKSOURCE) = 1 → такт от ядра (HCLK)
    SysTick->CTRL = 7;
}

// Точная задержка в миллисекундах
void delay_ms(uint32_t ms) {
    uint32_t start = msTicks;
    while ((msTicks - start) < ms) { }
}

// ============================================================
// PWM на TIM2
// ============================================================

void PWM_Init(void) {
    // 1. Включаем тактирование TIM2 (APB1) и GPIOA (APB2)
    RCC->APB1ENR |= RCC_APB1ENR_TIM2EN;   // TIM2 на APB1
    RCC->APB2ENR |= RCC_APB2ENR_IOPAEN;   // GPIOA на APB2

    // 2. Настраиваем PA0 как alternate function push-pull
    // PA0 — биты 0-3 в CRL (пины 0-7).
    // MODE = 10 (выход, 2 МГц), CNF = 10 (AF push-pull).
    // Итого: 0b1010 = 0xA.
    LED_PORT->CRL &= ~(0xF << 0);  // Очистить биты 0-3
    LED_PORT->CRL |=  (0xA << 0);  // Установить 0b1010

    // 3. Настраиваем TIM2
    // Частота таймера = 8 МГц / (PSC + 1) = 1 МГц
    TIM2->PSC = 7;              // Делитель 8 (8 МГц → 1 МГц)

    // Период = (ARR + 1) тактов = 1000
    // Частота ШИМ = 1 МГц / 1000 = 1000 Гц
    TIM2->ARR = PWM_STEPS - 1;  // 999

    // Начальная скважность = 0 (светодиод выключен)
    TIM2->CCR1 = 0;

    // 4. Я не очень понимаю что это но судя по reference manual и примерам
    // из инета это нужно
    TIM2->CCMR1 &= ~(0xFF << 0);
    TIM2->CCMR1 |=  (0x64 << 0);

    // 5. Включаем выход канала 1
    TIM2->CCER |= TIM_CCER_CC1E;

    // 6. Включаем таймер
    TIM2->CR1 |= TIM_CR1_CEN;
}

// ============================================================
// main
// ============================================================

int main(void) {
    SysTick_Init();
    PWM_Init();

    while (1) {
        // Плавное увеличение яркости (0 → 999) за 1 сек
        for (uint32_t i = 0; i < PWM_STEPS; i++) {
            TIM2->CCR1 = i;
            delay_ms(STEP_DELAY);
        }

        // Плавное уменьшение яркости (999 → 0) за 1 сек
        for (uint32_t i = PWM_STEPS; i > 0; i--) {
            TIM2->CCR1 = i;
            delay_ms(STEP_DELAY);
        }
    }
}
